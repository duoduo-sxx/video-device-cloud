function seg(
  idx: number,
  start: number,
  key: keyof typeof SPEAKERS,
  text: string,
): TranscriptSegment {
  const sp = SPEAKERS[key]
  const end = Math.min(DUR - 2, start + Math.max(3.2, text.length * 0.26))
  return {
    id: `tr_${String(idx).padStart(3, '0')}`,
    start,
    end: Math.round(end * 10) / 10,
    text,
    speakerId: sp.id,
    speakerName: sp.name,
    confidence: Math.round((0.88 + ((idx * 7) % 10) * 0.011) * 1000) / 1000,
    keywords: [KW[idx % KW.length], KW[(idx * 3 + 5) % KW.length]],
  }
}

