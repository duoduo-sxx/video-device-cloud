import type { SearchHit, SearchPreset } from '../types'
import { videos } from './data'
import { coverUrl } from '../lib/utils'

type Raw = [string, number, number, number, SearchHit['matchType'], string, number, string]

const v = (id: string) => videos.find((x) => x.id === id)!

function build(raws: Raw[]): SearchHit[] {
  return raws.map((r, i) => {
    const video = v(r[0])
    return {
      id: `hit_${r[0]}_${i}_${Math.round(r[1])}`,
      videoId: video.id,
      videoTitle: video.title,
      coverUrl: video.coverUrl,
      start: r[1],
      end: r[2],
      score: r[6],
      matchType: r[4],
      snippet: r[5],
      thumbnailUrl: coverUrl(`${video.id}_${r[1]}`, 320, 180),
      reasons: [
        { type: '命中依据', content: r[7] },
        { type: '片段时间', content: `${Math.floor(r[1] / 60)} 分 ${r[1] % 60} 秒 起，持续 ${r[2] - r[1]} 秒` },
      ],
    }
  }).sort((a, b) => b.score - a.score)
}

